from typing import Protocol
from ..entity import Binding


class Capture(Protocol):
    def start(self) -> str: ...
    def stop(self, capture: str) -> None: ...
    def finish(self, capture: str) -> None: ...


class Recognizer(Protocol):
    def transcribe(self, capture: str) -> str: ...


class Herdr(Protocol):
    def inspect(self, pane: str, socket: str) -> Binding: ...
    def insert(self, binding: Binding, text: str) -> None: ...


class Replies(Protocol):
    def arm(self, binding: Binding) -> str: ...
    def commit(self, registration: str) -> None: ...
    def cancel(self, pane: str, socket: str) -> None: ...
    def revoke(self, registration: str) -> None: ...


class Speech(Protocol):
    def cancel(self) -> None: ...
    def prewarm(self) -> None: ...
